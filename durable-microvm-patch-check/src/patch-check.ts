// src/patch-check.ts
import { withDurableExecution, type DurableContext } from "@aws/durable-execution-sdk-js";
import {
  microvmSession,
  MicrovmError,
  MicrovmJobFailedError,
  MicrovmTimeoutError,
} from "@aws/durable-execution-sdk-js-extensions/compute/microvm";

interface SourceFile {
  path: string;
  content: string;
}

interface PatchEvent {
  patchId: string; // e.g. "extend-loan-42"
  files: SourceFile[]; // code generated by the AI agent, including tests
}

interface TestResult {
  passed: boolean;
  exitCode: number | null;
  durationMs: number;
  output: string;
}

type Verdict =
  | { patchId: string; status: "passed" | "failed"; test: TestResult }
  | { patchId: string; status: "error"; reason: string };

const imageArn = process.env.MICROVM_IMAGE_ARN!;
const roleArn = process.env.MICROVM_ROLE_ARN!;

export const handler = withDurableExecution(
  async (event: PatchEvent, context: DurableContext): Promise<Verdict> => {
    try {
      const test = await microvmSession<TestResult>(
        context,
        "patch-check",
        {
          imageIdentifier: imageArn,
          executionRoleArn: roleArn,
          timeout: { minutes: 30 }, // lifetime of the MicroVM (max. 8 hours)
        },
        async (vm, ctx) => {
          // Job 1: write the files. They stay in the MicroVM for job 2.
          const prepared = await vm.invoke<{ directory: string }>(
            ctx,
            "prepare",
            { patchId: event.patchId, files: event.files },
            { path: "/prepare", timeout: { minutes: 2 }, heartbeatTimeout: { seconds: 60 } },
          );

          // Job 2: run the tests, on the same file system
          return vm.invoke<TestResult>(
            ctx,
            "test",
            { directory: prepared.directory },
            { path: "/test", timeout: { minutes: 10 }, heartbeatTimeout: { seconds: 60 } },
          );
        },
      );

      return {
        patchId: event.patchId,
        status: test.passed ? "passed" : "failed",
        test,
      };
    } catch (error) {
      // Error classes are the same on the first run and on replay,
      // so this branching stays deterministic.
      if (error instanceof MicrovmTimeoutError) {
        return { patchId: event.patchId, status: "error", reason: "Timeout or MicroVM crashed" };
      }
      if (error instanceof MicrovmJobFailedError) {
        return { patchId: event.patchId, status: "error", reason: `Job failed: ${error.message}` };
      }
      if (error instanceof MicrovmError) {
        return { patchId: event.patchId, status: "error", reason: `MicroVM error: ${error.name}` };
      }
      throw error;
    }
  },
);
